"""Emit stencil_tables.h ( constexpr tables of StencilKernel( r ) for r = 1, 2 )."""
import sys
import numpy as np
sys.path.insert( 0, __file__.rsplit( "/", 1 )[ 0 ] )
from stencil2d import StencilKernel

def arr( name, ty, vals ):
    return f"    static constexpr {ty} {name}[] = {{ " + ", ".join( repr( float( v ) ) if ty == "double" else str( int( v ) ) for v in vals ) + " };\n"

out = [ "// generated by gen_tables.py\n#pragma once\n\ntemplate<int R> struct StencilTables;\n" ]
for r in [ 1, 2 ]:
    K = StencilKernel( r )
    D = len( K.dirs )
    s = f"\ntemplate<> struct StencilTables<{r}> {{\n"
    s += f"    static constexpr int D = {D}, nb_offsets = {len( K.offsets )}, nb_pairs = {len( K.pairs )};\n"
    s += arr( "dir_x", "double", K.dirs[ :, 0 ] ) + arr( "dir_y", "double", K.dirs[ :, 1 ] )
    s += arr( "dir_inv_norm", "double", 1 / np.linalg.norm( K.dirs, axis = 1 ) )
    ka = [ int( m * K.dirs[ d, 0 ] ) for d, m in K.offsets ]
    kb = [ int( m * K.dirs[ d, 1 ] ) for d, m in K.offsets ]
    s += arr( "off_dir", "int", [ d for d, m in K.offsets ] ) + arr( "off_m", "double", [ m for d, m in K.offsets ] )
    s += arr( "off_x", "int", ka ) + arr( "off_y", "int", kb )
    s += arr( "off_sqn", "double", [ a * a + b * b for a, b in zip( ka, kb ) ] )
    # pairs grouped by k ( already sorted )
    beg = np.searchsorted( K.pk, np.arange( D + 1 ) )
    s += arr( "pair_beg", "int", beg ) + arr( "pair_j", "int", K.pj ) + arr( "pair_l", "int", K.pl )
    s += arr( "pair_lam", "double", K.plam ) + arr( "pair_mu", "double", K.pmu )
    s += arr( "vinv", "double", K.vinv.ravel() )
    ax = { tuple( d ): i for i, d in enumerate( K.dirs.astype( int ).tolist() ) }
    s += f"    static constexpr int dir_px = {ax[ ( 1, 0 ) ]}, dir_mx = {ax[ ( -1, 0 ) ]}, dir_py = {ax[ ( 0, 1 ) ]}, dir_my = {ax[ ( 0, -1 ) ]};\n"
    s += "};\n"
    out.append( s )
open( sys.argv[ 1 ], "w" ).write( "".join( out ) )
